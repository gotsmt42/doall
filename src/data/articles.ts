/** "2026-09-01" → "1 ก.ย. 2569" — คำนวณเอง ไม่ใช้ toLocaleDateString (server กับเบราว์เซอร์ให้ผลต่างกัน → hydration error) */
export const thaiShortDate = (iso: string) => {
  const [y, m, d] = iso.split("-").map(Number);
  return `${d} ${THAI_MONTHS[m - 1]} ${y + 543}`;
};
